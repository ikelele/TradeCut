// Приведение тикера к единому виду — одно на всё приложение.
//
// Раньше эта функция была скопирована в пяти модулях (логи Vataga и
// TigerTrade, клиент скринера, его фильтры, приём из браузера) плюс отдельная
// обрезка в именах файлов. Разъехаться им ничего не мешало, и на нелатинском
// тикере это выстрелило: 龙虾USDT превращался в USDT, потому что всё, кроме
// A-Z0-9, вырезалось. Клип сохранялся под чужим именем, а позиции по разным
// монетам в принципе могли схлопнуться в одну.
//
// Поэтому оставляем ВСЕ буквы любых алфавитов и цифры, убирая только
// разделители: "USDC/USDT" и "USDCUSDT" по-прежнему сводятся к одному виду,
// а 龙虾USDT остаётся собой.
//
// Результат годится и для имени файла: ни разделителей путей, ни запрещённых
// в Windows символов после такой чистки не остаётся.
function normalizeSymbol(value) {
  return String(value ?? '').toUpperCase().replace(/[^\p{L}\p{N}]+/gu, '')
}

module.exports = { normalizeSymbol }
